"""Article 50(1) detector: finds LLM chat-completion calls wired into what looks like a
user-facing interface, and checks whether AI-disclosure language appears anywhere in the
same function.

Two things have to be true to flag anything, to keep false positives down:
1. The file imports a known LLM SDK, AND the call shape matches a known chat-completion
   pattern (openai's chat.completions.create, anthropic's messages.create, etc.)
2. The enclosing function looks user-facing -- either a web-framework route decorator
   (Flask/FastAPI/Django-style) or a function/class name containing a chat/bot/assistant
   word. A bare LLM call in a batch-processing script with neither signal is not flagged;
   that's a deliberate false-negative trade, not an oversight -- Article 50(1) only
   applies to systems that interact directly with natural persons.
"""

import ast
from collections import defaultdict
from pathlib import Path

from manifest.article50 import CHATBOT_DISCLOSURE
from manifest.detectors.base import Confidence, Finding

_LLM_SDK_IMPORTS = {"openai", "anthropic", "google.generativeai", "langchain_openai", "langchain_anthropic", "langchain"}

_CHAT_CALL_SUFFIXES = (
    "chat.completions.create",
    "chatcompletion.create",
    "messages.create",
    "generate_content",
)

_USER_FACING_NAME_WORDS = ("chat", "bot", "assistant", "conversation", "converse")
_ROUTE_DECORATOR_MARKERS = (".route", ".get", ".post", ".put", ".websocket", ".on_message")

_DISCLOSURE_PHRASES = (
    "ai assistant", "artificial intelligence", "chatbot", "chat bot",
    "you are chatting with", "you're chatting with", "you are talking to",
    "automated assistant", "automated system", "virtual assistant",
    "ai-powered", "powered by ai", "this is an ai", "talking to an ai",
    "generated by ai", "not a human", "an ai, not a human", "ai chat",
)


def _dotted_name(node: ast.AST) -> str:
    """Reconstruct 'client.chat.completions.create' from a Call node's func attribute chain."""
    parts = []
    while isinstance(node, ast.Attribute):
        parts.append(node.attr)
        node = node.value
    if isinstance(node, ast.Name):
        parts.append(node.id)
    return ".".join(reversed(parts))


def _imports_llm_sdk(tree: ast.Module) -> bool:
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            if any(alias.name.split(".")[0] in {"openai", "anthropic", "langchain_openai", "langchain_anthropic", "langchain"} or alias.name in _LLM_SDK_IMPORTS for alias in node.names):
                return True
        elif isinstance(node, ast.ImportFrom) and node.module:
            if node.module.split(".")[0] in {"openai", "anthropic", "langchain_openai", "langchain_anthropic", "langchain", "google"}:
                return True
    return False


def _is_chat_completion_call(call: ast.Call) -> bool:
    dotted = _dotted_name(call.func).lower()
    return any(dotted.endswith(suffix) for suffix in _CHAT_CALL_SUFFIXES)


def _looks_user_facing(func: ast.FunctionDef | ast.AsyncFunctionDef) -> bool:
    name = func.name.lower()
    if any(word in name for word in _USER_FACING_NAME_WORDS):
        return True
    for dec in func.decorator_list:
        dec_src = ast.dump(dec).lower()
        if any(marker.strip(".") in dec_src for marker in _ROUTE_DECORATOR_MARKERS):
            return True
    return False


class _FuncScopeVisitor(ast.NodeVisitor):
    """Collects calls and string literals per enclosing function, since ast has no
    built-in parent pointers -- a stack of the current function(s) does the job.
    """

    def __init__(self) -> None:
        self.func_stack: list[ast.FunctionDef | ast.AsyncFunctionDef] = []
        self.calls_by_func: dict[ast.AST, list[ast.Call]] = defaultdict(list)
        self.literals_by_func: dict[ast.AST, list[str]] = defaultdict(list)

    def _visit_func(self, node: ast.FunctionDef | ast.AsyncFunctionDef) -> None:
        self.func_stack.append(node)
        self.generic_visit(node)
        self.func_stack.pop()

    def visit_FunctionDef(self, node: ast.FunctionDef) -> None:
        self._visit_func(node)

    def visit_AsyncFunctionDef(self, node: ast.AsyncFunctionDef) -> None:
        self._visit_func(node)

    def visit_Call(self, node: ast.Call) -> None:
        if self.func_stack:
            self.calls_by_func[self.func_stack[-1]].append(node)
        self.generic_visit(node)

    def visit_Constant(self, node: ast.Constant) -> None:
        if isinstance(node.value, str) and self.func_stack:
            self.literals_by_func[self.func_stack[-1]].append(node.value)


def scan_file(path: Path) -> list[Finding]:
    source = path.read_text(encoding="utf-8", errors="replace")
    try:
        tree = ast.parse(source, filename=str(path))
    except SyntaxError:
        return []

    if not _imports_llm_sdk(tree):
        return []

    source_lines = source.splitlines()
    visitor = _FuncScopeVisitor()
    visitor.visit(tree)

    findings: list[Finding] = []
    for func, calls in visitor.calls_by_func.items():
        chat_calls = [c for c in calls if _is_chat_completion_call(c)]
        if not chat_calls or not _looks_user_facing(func):
            continue

        literals = " ".join(visitor.literals_by_func.get(func, [])).lower()
        has_disclosure = any(phrase in literals for phrase in _DISCLOSURE_PHRASES)

        call = chat_calls[0]
        snippet = source_lines[call.lineno - 1].strip() if 0 < call.lineno <= len(source_lines) else ""
        findings.append(
            Finding(
                file=str(path),
                line=call.lineno,
                provision=CHATBOT_DISCLOSURE,
                confidence=Confidence.needs_review if has_disclosure else Confidence.likely_violation,
                detail=(
                    f"'{func.name}' calls {_dotted_name(call.func)} and looks user-facing "
                    f"(function name/decorator suggests a chat interface). "
                    + ("AI-disclosure language was found in this function's strings -- verify it's actually shown to the user before/at first interaction."
                       if has_disclosure else
                       "No AI-disclosure language (e.g. 'AI assistant', 'chatbot') found anywhere in this function.")
                ),
                snippet=snippet,
            )
        )
    return findings

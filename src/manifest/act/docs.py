"""Annex IV technical-documentation scaffold, generated from the system profile.

What it does: lays out every Annex IV section in order, pre-fills what the profile already
knows, links each section to the checklist item that carries its evidence, and counts how many
sections still say TODO, so documentation completeness can be a CI gate.

What it does not do: write the documentation. The substance of an Annex IV file (data
provenance, validation results, risk analysis) comes from the engineering work. A scaffold that
says "TODO" in the right place is more useful than prose invented to fill the gap, and the
completeness count never treats generated filler as an answer.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from manifest.act import data
from manifest.act.checklist import Checklist
from manifest.act.classify import Classification
from manifest.act.profile import SystemProfile
from manifest.detectors.base import Confidence, Finding

# Annex IV sections whose evidence is tracked by a checklist item.
SECTION_ITEM = {"2d": "art10", "2e": "art14", "2g": "art15", "2h": "art15", "5": "art9", "8": "art47", "9": "art72"}
TODO = "TODO"


@dataclass
class Completeness:
    total: int
    filled: int
    missing: list[str] = field(default_factory=list)

    @property
    def percent(self) -> float:
        return 100.0 * self.filled / self.total if self.total else 100.0

    @property
    def complete(self) -> bool:
        return self.filled == self.total


def _prefill(p: SystemProfile) -> dict[str, str]:
    out: dict[str, str] = {}
    if p.intended_purpose and p.provider and p.version:
        out["1a"] = f"Intended purpose: {p.intended_purpose}\nProvider: {p.provider}\nVersion: {p.version}"
    return out


def completeness(p: SystemProfile) -> Completeness:
    answers = {**_prefill(p), **{k: v for k, v in p.documentation.items() if v.strip()}}
    missing = [s.id for s in data.ANNEX_IV if not answers.get(s.id, "").strip()]
    return Completeness(total=len(data.ANNEX_IV), filled=len(data.ANNEX_IV) - len(missing), missing=missing)


def count_todos(markdown: str) -> int:
    """TODO markers left in an edited document (for teams that fill the Markdown, not the YAML)."""
    return sum(1 for line in markdown.splitlines() if line.strip().startswith(f"{TODO}:") or line.strip() == TODO)


def _scan_summary(findings: list[Finding]) -> str:
    art50 = [f for f in findings if f.provision.citation in ("Article 50(1)", "Article 50(2)")]
    likely = sum(f.confidence == Confidence.likely_violation for f in art50)
    review = sum(f.confidence == Confidence.needs_review for f in art50)
    return f"Static scan: {likely} likely violation(s) and {review} item(s) needing review for Article 50(1)/(2). " \
           "A scan cannot verify that a disclosure is shown or that a marking survives re-encoding."


def render(p: SystemProfile, c: Classification, checklist: Checklist | None = None,
           findings: list[Finding] | None = None, today: str = "") -> tuple[str, Completeness | None]:
    head = [
        f"# Technical documentation: {p.name}",
        "",
        ("> Scaffold generated by `manifest act docs`. It structures the documentation and shows what is missing; "
         "it does not make the system compliant, and it is not legal advice."),
        "",
        f"- System: **{p.name}** {p.version}".rstrip(),
        f"- Classification: **{c.tier.replace('_', ' ')}**" + (f"  (generated {today})" if today else ""),
        "",
    ]
    if c.tier == "not_high_risk_documented":
        return "\n".join(head + _art6_4_record(p, c)), None
    if c.tier != "high_risk":
        head += [
            ("Annex IV technical documentation is required for **high-risk** systems (Art. 11). This system is classified "
             f"`{c.tier}`, so no Annex IV file is required; keep the records its own regime asks for "
             "(see `manifest act checklist`)."),
            "",
        ]
        return "\n".join(head), None

    comp = completeness(p)
    head += [f"- Completeness: **{comp.filled}/{comp.total}** Annex IV sections answered ({comp.percent:.0f}%)", ""]
    answers = {**_prefill(p), **{k: v for k, v in p.documentation.items() if v.strip()}}
    prefilled = set(_prefill(p)) - set(p.documentation)
    body: list[str] = []
    for s in data.ANNEX_IV:
        body += [f"## {s.id}. {s.title}", "", f"*{s.ref}.* {s.prompt}", ""]
        item_id = SECTION_ITEM.get(s.id)
        if item_id and checklist is not None:
            try:
                it = checklist.get(item_id)
                body += [f"Related checklist item: `{it.id}` ({it.citation}), status **{it.status}**"
                         + (f", evidence: {it.evidence}" if it.evidence else ""), ""]
            except KeyError:
                pass
        ans = answers.get(s.id, "").strip()
        if ans:
            body += [ans, ""] + (["*(pre-filled from the profile)*", ""] if s.id in prefilled else [])
        else:
            body += [f"{TODO}: {s.prompt}", ""]
        if s.id == "3" and findings is not None:
            body += [_scan_summary(findings), ""]
    return "\n".join(head + body), comp


def _art6_4_record(p: SystemProfile, c: Classification) -> list[str]:
    points = ", ".join(p.annex_iii) or "(none)"
    conds = [data.DEROGATION_CONDITIONS[x] for x in p.derogation_conditions]
    lines = [
        "## Article 6(4) assessment record",
        "",
        ("The provider concludes that this Annex III system is **not high-risk** under Article 6(3). That conclusion must be "
         "documented before placing the system on the market or putting it into service, and given to national "
         "competent authorities on request. The system must still be registered (Art. 49(2))."),
        "",
        f"- Annex III use case(s) concerned: {points}",
        f"- Profiling of natural persons: {'yes (derogation unavailable)' if p.profiling else 'no'}",
        "- Conditions relied on:",
        *[f"  - {x}" for x in conds],
        ("- Declared conclusion of no significant risk of harm to health, safety or fundamental rights: "
         f"{'yes' if p.no_significant_risk else 'NO'}"),
        "",
        f"{TODO}: Explain why the system does not materially influence the outcome of decisions, with evidence.",
        "",
        f"{TODO}: Assessor, date, and review date.",
        "",
    ]
    return lines
